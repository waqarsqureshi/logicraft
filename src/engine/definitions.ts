/**
 * Helper to generate pins with accurate relative coordinates
 */
export function createComponentPins(
  type: GateType,
  width: number,
  height: number,
  componentId: string
) {
  const def = COMPONENT_DEFINITIONS[type];
  const inputs = def.defaultInputs.map((inp, idx) => {
    const spacing = height / (def.defaultInputs.length + 1);
    const y = spacing * (idx + 1);
    return {
      id: `${componentId}_in_${idx}`,
      name: inp.name,
      type: 'input' as const,
      index: idx,
      value: 'Z' as const,
      voltage: 0,
      relativeX: 0,
      relativeY: y,
    };
  });

  const outputs = def.defaultOutputs.map((out, idx) => {
    const spacing = height / (def.defaultOutputs.length + 1);
    const y = spacing * (idx + 1);
    return {
      id: `${componentId}_out_${idx}`,
      name: out.name,
      type: 'output' as const,
      index: idx,
      value: 0 as const,
      voltage: 0,
      relativeX: width,
      relativeY: y,
    };
  });

  return { inputs, outputs };
}
